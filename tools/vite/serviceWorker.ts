/**
 * Writes `sw.js` into a production build: a small service worker that keeps the whole game (every
 * built file, the fonts, icons and manifest) in the browser's cache so it starts and plays offline.
 * - Built files have their content hash in the name, so they're served from the cache first.
 * - The page itself (index.html) is fetched fresh when online and falls back to the cached copy
 *   offline, so a new version reaches players the next time they open the game online.
 * - The cache is named after the build, and older caches are deleted when a new worker takes over.
 * A new worker waits until every tab of the old version is closed, so a running game never loses files.
 * Every path is relative to the worker's own folder, so the game works at a site's root or in a
 * sub-folder (GitHub Pages serves it at /<repository>/).
 */
import { readdirSync } from 'node:fs';
import type { Plugin } from 'vite';

/** Folders and files from public/ to cache too (licence texts are left out). */
const PUBLIC_DIRS = ['fonts', 'icons'];
const PUBLIC_FILES = ['manifest.webmanifest'];
const CACHE_PREFIX = 'lighthouse-keeper-';

/** A short, stable name for a list of file names (they already carry content hashes). */
function hashOf(names: readonly string[]): string {
  let h = 2166136261;
  for (const ch of names.join('|')) {
    h ^= ch.charCodeAt(0);
    h = Math.imul(h, 16777619);
  }
  return (h >>> 0).toString(36);
}

function workerSource(cache: string, files: readonly string[]): string {
  return `// Generated by tools/vite/serviceWorker.ts. Keeps Lighthouse Keeper playable offline.
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(files)};
// Servers often send "Vary: Origin"; scripts and fonts are requested in CORS mode, so match by URL alone.
const MATCH = { ignoreVary: true };
// The game's own page: the folder this worker lives in.
const PAGE = new URL('./', self.location.href).href;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(${JSON.stringify(CACHE_PREFIX)}) && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    // The page: fresh when online (and remembered), the cached copy when offline.
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            event.waitUntil(caches.open(CACHE).then((cache) => cache.put(PAGE, copy)));
          }
          return response;
        })
        .catch(() => caches.match(PAGE, MATCH).then((hit) => hit || Response.error())),
    );
    return;
  }
  event.respondWith(caches.match(request, MATCH).then((hit) => hit || fetch(request)));
});
`;
}

export function serviceWorker(): Plugin {
  return {
    name: 'lighthouse-keeper-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const built = Object.keys(bundle).filter((name) => !name.endsWith('.map'));
      const fromPublic = [
        ...PUBLIC_FILES,
        ...PUBLIC_DIRS.flatMap((dir) =>
          readdirSync(`public/${dir}`)
            .filter((name) => !name.endsWith('.txt'))
            .map((name) => `${dir}/${name}`),
        ),
      ];
      const files = ['./', ...[...built, ...fromPublic].map((name) => `./${name}`)].sort();
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: workerSource(`${CACHE_PREFIX}${hashOf(files)}`, files),
      });
    },
  };
}
